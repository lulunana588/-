def get_client():
    creds = Credentials.from_service_account_file(SERVICE_ACCOUNT_FILE, scopes=SCOPES)
    return gspread.authorize(creds)


def get_or_create_worksheet(sh, title, rows=200, cols=10):
    try:
        ws = sh.worksheet(title)
    except gspread.exceptions.WorksheetNotFound:
        ws = sh.add_worksheet(title=title, rows=str(rows), cols=str(cols))
    return ws


def build_rows(entries):
    rows = []
    for name, telco, number, plan, is_stock, note in entries:
        plan_type = "月租型" if plan == "月租" else "充值型"
        type_col = "庫存" if is_stock else ""
        rows.append([name, telco, number, plan_type, type_col, note or ""])
    return rows


def push_sheet(sh, tab_name, entries):
    ws = get_or_create_worksheet(sh, tab_name)
    ws.clear()
    rows = [HEADERS] + build_rows(entries)
    ws.update("A1", rows, value_input_option="USER_ENTERED")
    print(f"[OK] {tab_name} 已寫入 {len(rows) - 1} 筆")


def main():
    client = get_client()
    sh = client.open_by_key(SPREADSHEET_ID)
    for tab_name, entries in DATA.items():
        if not entries:
            print(f"[SKIP] {tab_name} 沒有資料，請先在 DATA 區塊填入")
            continue
        push_sheet(sh, tab_name, entries)


if __name__ == "__main__":
    main()
